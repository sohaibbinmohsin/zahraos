// De-duplicate by id (the Punjab block has a couple of intentional repeats
// while hand-compiling) so the dropdown never shows the same city twice.
const ALL = [...PUNJAB, ...SINDH, ...KP, ...BALOCHISTAN, ...ICT, ...AJK, ...GB];
const seen = new Set<string>();
const deduped = ALL.filter((c) => {
  if (seen.has(c.id)) return false;
  seen.add(c.id);
  return true;
});

// Big metros float to the top of the (otherwise alphabetical) list so the
// most common picks are one glance away when the dropdown opens.
const FEATURED = [
  "karachi", "lahore", "islamabad", "rawalpindi", "faisalabad", "multan",
  "peshawar", "quetta", "gujranwala", "hyderabad", "sialkot", "bahawalpur",
  "sargodha", "sukkur", "abbottabad", "muzaffarabad", "gilgit", "mirpur",
];
const featuredRank = new Map(FEATURED.map((id, i) => [id, i]));

export const PAKISTAN_CITIES: CityOption[] = [...deduped].sort((a, b) => {
  const ra = featuredRank.get(a.id);
  const rb = featuredRank.get(b.id);
  if (ra !== undefined || rb !== undefined) {
    return (ra ?? Number.MAX_SAFE_INTEGER) - (rb ?? Number.MAX_SAFE_INTEGER);
  }
  return a.label.localeCompare(b.label);
});

export function filterCities(query: string): CityOption[] {
  const q = query.trim().toLowerCase();
  if (!q) return PAKISTAN_CITIES;

  return PAKISTAN_CITIES.filter((city) => {
    if (city.label.toLowerCase().includes(q)) return true;
    if (city.secondary && city.secondary.toLowerCase().includes(q)) return true;
    if (city.aliases && city.aliases.some((a) => a.toLowerCase().includes(q))) return true;
    return false;
  });
}
