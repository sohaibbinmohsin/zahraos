export interface CityOption {
  id: string;
  label: string;
  secondary?: string;
  aliases?: string[];
}

function mk(label: string, secondary: string, aliases?: string[]): CityOption {
  return {
    id: label.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, ""),
    label,
    secondary,
    ...(aliases ? { aliases } : {}),
  };
}

